/*
 * The two chevrons that stand in for the "s" overlap each other. Flat, the
 * artwork separates them by shading; in 3D they are pulled apart in z instead,
 * so the mark actually interlocks.
 */
export const CHEVRONS = { front: 3, back: 4 };

const SVG_NS = 'http://www.w3.org/2000/svg';

/* All contours as one path, so a single <use> carries the whole wordmark. */
export const MARK_PATH = MARK_CONTOURS
  .map((loop) => `M${loop.map(([x, y]) => `${x},${y}`).join('L')}Z`)
  .join('');

/* Fills a <g> with the mark, for the page's <use href="#riskyMark"> references. */
export function buildRiskyMark(hostId = 'riskyMark') {
  const group = document.getElementById(hostId);
  if (!group || group.childElementCount) return group;

  const path = document.createElementNS(SVG_NS, 'path');
  path.setAttribute('d', MARK_PATH);
  group.appendChild(path);
  return group;
}
